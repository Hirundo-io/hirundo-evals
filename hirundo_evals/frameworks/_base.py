import contextlib
import csv
import logging
import os
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any, TypedDict, get_type_hints

OutputEntry = TypedDict(
    "OutputEntry",
    {
        "Run ID": str,
        "Framework": str,
        "Benchmark": str,
        "Metric": str,
        "Score": float | str,
        "Runtime (sec)": int | str,
    },
)


@contextlib.contextmanager
def _preserve_logging_handlers():
    loggers: list[logging.Logger] = [logging.root]
    loggers.extend(
        logger
        for logger in logging.root.manager.loggerDict.values()
        if isinstance(logger, logging.Logger)
    )
    states = {
        logger: (
            logger.handlers.copy(),
            logger.level,
            logger.propagate,
            logger.disabled,
        )
        for logger in loggers
    }
    try:
        yield
    finally:
        current_loggers: list[logging.Logger] = [logging.root]
        current_loggers.extend(
            logger
            for logger in logging.root.manager.loggerDict.values()
            if isinstance(logger, logging.Logger)
        )
        for logger in current_loggers:
            state = states.get(logger)
            if state is None:
                logger.handlers.clear()
                continue
            handlers, level, propagate, disabled = state
            logger.handlers[:] = handlers
            logger.setLevel(level)
            logger.propagate = propagate
            logger.disabled = disabled


class BaseEvalFrameworkWrapper(ABC):
    """
    Base class for evaluation framework wrappers.

    Args:
        model: The model to evaluate.
        tasks: The tasks/benchmarks to evaluate.
        output_dir: The directory in which to save the summary CSV.
        log_dir: The directory in which to save the outputs.
    """

    def __init__(self, model: str, tasks: list[str], output_dir: Path, log_dir: Path):
        self.model = model
        self.tasks = tasks
        self.output_path = str(output_dir / "results.csv")
        self.log_dir = str(log_dir)

    @abstractmethod
    def run_eval(
        self,
        model: str | None = None,
        model_base_url: str | None = None,
        extra: list[str] | None = None,
    ) -> Any | None:
        """
        Run the framework evaluation.

        Args:
            model: Optional model override.
            model_base_url: Optional base URL for the model. Required when the model is
                hosted externally.
            extra: Extra arguments to pass to the framework.

        Returns:
            Any artifacts generated by the framework (optional).
        """
        raise NotImplementedError

    def run(
        self,
        model: str | None = None,
        model_base_url: str | None = None,
        extra: list[str] | None = None,
    ) -> None:
        """
        Run the framework.

        Args:
            model: Optional model override.
            model_base_url: Optional base URL for the model. Required when the model is
                hosted externally.
            extra: Extra arguments to pass to the framework.
        """
        with _preserve_logging_handlers():
            outputs = self.run_eval(model, model_base_url, extra)
        logging.info(f"✅ Evaluation complete! Logs saved to: {self.log_dir}")
        self.export_results(outputs, self.output_path)
        logging.info(f"✅ Summary metrics successfully written to {self.output_path}")

    @abstractmethod
    def prepare_results(self, outputs: Any | None) -> list[OutputEntry]:
        """
        Prepare the results of the evaluation for CSV export.

        Args:
            outputs (optional): The outputs of the evaluation.

        Returns:
            The results of the evaluation for CSV export.
        """
        raise NotImplementedError

    @staticmethod
    def _format_output_row(row: OutputEntry) -> dict[str, object]:
        formatted_row = dict(row)
        score = formatted_row.get("Score")
        if isinstance(score, int | float):
            formatted_row["Score"] = f"{score:.2f}"

        return formatted_row

    def export_results(self, outputs: Any | None, output_path: str) -> None:
        """
        Export the results of the evaluation to a CSV file.

        Args:
            outputs (optional): The outputs of the evaluation.
            output_path: The path to the output CSV file.
        """
        # Prepare the results for CSV export
        results = [
            self._format_output_row(row) for row in self.prepare_results(outputs)
        ]
        fieldnames = list(get_type_hints(OutputEntry).keys())
        try:
            existing_fieldnames: list[str] = []
            existing_rows: list[dict[str, str]] = []
            should_write_header = True
            # Get existing rows and fieldnames if the file exists
            if os.path.isfile(output_path) and os.path.getsize(output_path) > 0:
                with open(output_path, newline="", encoding="utf-8") as f:
                    reader = csv.DictReader(f)
                    existing_fieldnames = list(reader.fieldnames or [])
                    existing_rows = list(reader)
                should_write_header = existing_fieldnames != fieldnames
            # Rewrite an existing file if the header has changed
            if should_write_header and existing_rows:
                # Get the ordered union of the new and existing fieldnames
                # (this is the most efficient way to do this)
                fieldnames = list(dict.fromkeys(fieldnames + existing_fieldnames))
                with open(output_path, mode="w", newline="", encoding="utf-8") as f:
                    writer = csv.DictWriter(f, fieldnames=fieldnames, restval="N/A")
                    writer.writeheader()
                    writer.writerows(
                        {
                            fieldname: row.get(fieldname, "N/A")
                            for fieldname in fieldnames
                        }
                        for row in existing_rows
                    )
                should_write_header = False
            # Append to CSV, writing the header only for new, empty, or migrated files
            with open(output_path, mode="a", newline="", encoding="utf-8") as f:
                writer = csv.DictWriter(f, fieldnames=fieldnames)
                if should_write_header:
                    writer.writeheader()
                writer.writerows(results)
        except Exception as e:
            raise Exception(f"Failed to write CSV file: {e}") from e
